export default function useTranslation() {
  const { language, isRTL } = useTheme();

  const t = (key: string) => {
    if (!dictionary[key]) {
      console.warn(`Missing translation for key: "${key}"`);
      return key;
    }
    return dictionary[key][language];
  };

  return { t, lang: language, isRtl: isRTL };
}
